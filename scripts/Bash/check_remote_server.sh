#!/bin/bash
# шебанг — говорит системе, каким интерпретатором запускать этот файл
#bash scripts/connectSSH.sh
error() {
  # объявляем функцию error — единая точка для "сообщить об ошибке и остановиться"
  echo "ERROR: $*" >&2
  # $*  — все аргументы, с которыми вызвали error, склеенные в одну строку
  # >&2 — выводим в stderr (поток ошибок), а не в обычный вывод
  exit 1
  # останавливает ВЕСЬ скрипт (не только функцию) с кодом 1 = "ошибка"
}

# -----------------------------------------------------------------------
# ФАЗА ВЫБОРА
# -----------------------------------------------------------------------
# Раньше был один флаг CONNECT_MODE (0/1). Теперь вместо флага делаем
# полноценное меню: пользователь сам решает, что хочет сделать —
# просто проверить сервер, зайти по SSH, или открыть туннель на порт
# (например Grafana), не трогая код каждый раз руками.

show_menu() {
  # функция, которая просто печатает меню на экран — ничего не решает сама
  echo "==============================="
  echo " Что делаем?"
  echo "==============================="
  echo " 1) Проверить сервер (зайти и сразу выйти + показать содержимое папки)"
  echo " 2) Подключиться по SSH (зайти и остаться в сессии)"
  echo " 3) Открыть туннель на порт (например Grafana на 3000)"
  echo " 0) Выход"
  echo "==============================="
}

show_menu
# вызываем функцию — печатаем меню один раз перед тем как спросить выбор

read -rp "Введи номер: " CHOICE
# read       — читает то, что пользователь напечатает в терминале
# -r         — не трогать обратные слэши \ как спецсимволы (raw режим)
# -p "текст" — сразу показать текст-подсказку перед вводом
# CHOICE     — сюда попадёт то, что пользователь ввёл (например "1")

if [[ "$CHOICE" == "0" ]]; then
  # если выбрали "Выход" — завершаем скрипт сразу, дальше ничего не делаем
  echo "Пока!"
  exit 0
fi

if [[ "$CHOICE" != "1" && "$CHOICE" != "2" && "$CHOICE" != "3" ]]; then
  # проверяем что ввели именно один из ожидаемых номеров
  # != означает "не равно", && значит "и" — то есть условие сработает,
  # если ЧИСЛО НЕ равно 1 И НЕ равно 2 И НЕ равно 3 (то есть что-то левое)
  error "Неверный выбор: $CHOICE. Нужно ввести 1, 2, 3 или 0"
fi

# -----------------------------------------------------------------------
# ЗАГРУЗКА .env (без изменений от твоей исходной версии)
# -----------------------------------------------------------------------
if [[ -f ".env" ]]; then
  # -f ".env" — проверка "существует ли обычный файл .env рядом со скриптом"
  echo "file is exist"
  source .env
  # выполняет .env как баш-код — переменные из файла становятся доступны дальше
  echo "SSH_HOST = $SSH_HOST"
  echo "SSH_KEY_PATH=$SSH_KEY_PATH"
  echo "SSH_USER = $SSH_USER"
  echo "REMOTE_DIR = $REMOTE_DIR"
  # печатаем что реально загрузилось — проверка глазами, что .env не пустой
else
  error ".env файл не найден"
  # если файла нет — сразу зовём error, скрипт останавливается здесь же
fi

# TUNNEL_PORT — новая переменная, тоже можно задать в .env, иначе
# подставится 3000 по умолчанию (порт Grafana)
TUNNEL_PORT="${TUNNEL_PORT:-3000}"
# ${VAR:-значение} — если VAR не задана или пустая, используем "значение"

# -----------------------------------------------------------------------
# ВАРИАНТ 1: просто проверить сервер (старое поведение скрипта без флага)
# -----------------------------------------------------------------------
if [[ "$CHOICE" == "1" ]]; then

  ssh -i "$SSH_KEY_PATH" "$SSH_USER@$SSH_HOST" exit
  # -i "$SSH_KEY_PATH"    — использовать этот приватный ключ для входа
  # "$SSH_USER@$SSH_HOST" — куда логинимся
  # exit                  — команда, которая выполнится СРАЗУ на сервере после
  #                         входа: зайти и сразу выйти. Нам тут нужен только
  #                         факт подключения, не реальная сессия

  if [[ $? -ne 0 ]]; then
    # $?    — код возврата ПОСЛЕДНЕЙ выполненной команды (это ssh выше)
    # -ne 0 — "не равно нулю" (0 = успех, всё остальное = ошибка)
    error "не удалось подключиться"
  fi

  echo "Подключение прошло успешно"

  echo "Содержимое $REMOTE_DIR на сервере:"
  ssh -i "$SSH_KEY_PATH" "$SSH_USER@$SSH_HOST" "cd \"$REMOTE_DIR\" && ls -a"
  # ⚠️ это ОДНА команда ssh с текстом-командой в кавычках как аргумент.
  # "cd ... && ls -a" выполняется НА СЕРВЕРЕ, в рамках этого же ssh-запроса —
  # && — "и, если первая команда прошла успешно": ls запустится только
  # если cd в нужную папку реально сработал

fi

# -----------------------------------------------------------------------
# ВАРИАНТ 2: подключиться и остаться внутри SSH-сессии (раньше был --connect)
# -----------------------------------------------------------------------
if [[ "$CHOICE" == "2" ]]; then

  echo "Захожу на $SSH_USER@$SSH_HOST ..."
  exec ssh -i "$SSH_KEY_PATH" "$SSH_USER@$SSH_HOST"
  # exec ЗАМЕНЯЕТ процесс скрипта процессом ssh (а не запускает рядом).
  # После этой строки скрипт перестаёт существовать — ты оказываешься
  # прямо внутри интерактивной SSH-сессии на сервере

fi

# -----------------------------------------------------------------------
# ВАРИАНТ 3: открыть туннель на порт (например Grafana)
# -----------------------------------------------------------------------
if [[ "$CHOICE" == "3" ]]; then

  echo "На какой порт открыть туннель? (Enter = $TUNNEL_PORT по умолчанию)"
  read -rp "Порт: " CUSTOM_PORT
  # если пользователь просто нажал Enter не вводя ничего — CUSTOM_PORT будет пустой

  if [[ -n "$CUSTOM_PORT" ]]; then
    # -n "$STR" — true, если строка НЕ пустая
    TUNNEL_PORT="$CUSTOM_PORT"
    # если пользователь ввёл свой порт — используем его вместо порта по умолчанию
  fi

  if ss -tulpn 2>/dev/null | grep -q ":$TUNNEL_PORT "; then
    # проверяем, не занят ли уже этот порт у нас локально
    error "Локальный порт $TUNNEL_PORT уже занят чем-то другим"
  fi

  echo "Открываю туннель: localhost:$TUNNEL_PORT -> $SSH_HOST:$TUNNEL_PORT"
  echo "После подключения открой в браузере: http://localhost:$TUNNEL_PORT"
  echo "Нажми Ctrl+C, чтобы закрыть туннель."

  ssh -i "$SSH_KEY_PATH" \
      -L "$TUNNEL_PORT:localhost:$TUNNEL_PORT" \
      -o ServerAliveInterval=60 \
      -N \
      "$SSH_USER@$SSH_HOST"
  # -L локальный_порт:localhost:удалённый_порт — проброс порта
  # -N                     — не выполнять команду на сервере, просто держать туннель
  # -o ServerAliveInterval — пинговать сервер каждые 60 сек, чтобы туннель не отваливался

fi